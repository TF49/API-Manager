#!/usr/bin/env bash
# API Manager — install / upgrade on a Linux server that already has Node.js 20.9+, MySQL and Nginx.
#
#   sudo bash deploy/install.sh
#
# Safe to re-run: the first run installs, later runs upgrade (rebuild, migrate, restart)
# and keep the existing secrets, database and certificate.
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SERVICE=api-manager
SERVICE_USER=apimanager
ENV_FILE="$APP_DIR/.env.production.local"
STATE_FILE="$APP_DIR/deploy/.install-state"
CERT_DIR=/etc/nginx/ssl/api-manager
NGINX_CONF=/etc/nginx/conf.d/api-manager.conf

c_ok()   { printf '\033[32m✔ %s\033[0m\n' "$*"; }
c_info() { printf '\033[36m➜ %s\033[0m\n' "$*"; }
c_warn() { printf '\033[33m! %s\033[0m\n' "$*"; }
die()    { printf '\033[31m✖ %s\033[0m\n' "$*" >&2; exit 1; }
ask()    { local v; read -r -p "$1 [$2]: " v </dev/tty; echo "${v:-$2}"; }
rand()   { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c "${1:-40}"; }

[[ $EUID -eq 0 ]] || die "请用 root 运行：sudo bash deploy/install.sh"
cd "$APP_DIR"
[[ -f package.json && -f next.config.ts ]] || die "没找到项目文件，请在项目目录里运行"
umask 022   # files we create (build output) must stay readable by the service user

# ---------------------------------------------------------------- 1. prerequisites
c_info "检查环境"
for bin in node npm nginx openssl mysql; do
  command -v "$bin" >/dev/null || die "缺少 $bin，请先安装"
done
NODE_BIN="$(readlink -f "$(command -v node)")"
NODE_VER="$(node -p 'process.versions.node')"
node -e 'const [a,b]=process.versions.node.split(".").map(Number);process.exit(a>20||(a===20&&b>=9)?0:1)' \
  || die "Node.js 版本是 $NODE_VER，需要 20.9 或更高"
c_ok "Node $NODE_VER ($NODE_BIN)、npm、nginx、openssl、mysql 客户端都在"

# Remembered answers from a previous run.
# shellcheck disable=SC1090
[[ -f "$STATE_FILE" ]] && source "$STATE_FILE"

# ---------------------------------------------------------------- 2. questions (first run only)
if [[ -z "${PUBLIC_IP:-}" ]]; then
  DETECTED_IP="$(curl -fsS --max-time 5 https://api.ipify.org 2>/dev/null || hostname -I | awk '{print $1}')"
  PUBLIC_IP="$(ask '服务器公网 IP' "$DETECTED_IP")"
  HTTPS_PORT="$(ask '对外 HTTPS 端口（避免和服务器上已有网站的 443 冲突）' 8443)"
  APP_PORT="$(ask 'Next.js 内部监听端口（只监听 127.0.0.1）' 3100)"
fi
[[ "$PUBLIC_IP" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "IP 格式不对：$PUBLIC_IP"
if [[ "$HTTPS_PORT" == 443 ]]; then ORIGIN="https://$PUBLIC_IP"; else ORIGIN="https://$PUBLIC_IP:$HTTPS_PORT"; fi

# ---------------------------------------------------------------- 3. service user
if ! id "$SERVICE_USER" >/dev/null 2>&1; then
  useradd --system --no-create-home --home-dir /nonexistent --shell /usr/sbin/nologin "$SERVICE_USER"
  c_ok "已创建系统用户 $SERVICE_USER"
fi
RUN_AS="$SERVICE_USER"
if ! runuser -u "$SERVICE_USER" -- test -x "$NODE_BIN"; then
  # Typical for nvm installs under /root: the service user can't reach that node binary.
  c_warn "$SERVICE_USER 无法执行 $NODE_BIN（多半是 nvm 装在 /root 下），服务将以 root 运行。"
  c_warn "更安全的做法：用系统包管理器或 NodeSource 安装 Node 到 /usr/bin，然后重跑本脚本。"
  RUN_AS=root
fi

# ---------------------------------------------------------------- 4. database + env file
if [[ ! -f "$ENV_FILE" ]]; then
  c_info "配置数据库"
  DB_HOST="$(ask 'MySQL 地址' 127.0.0.1)"
  DB_PORT="$(ask 'MySQL 端口' 3306)"
  DB_NAME="$(ask '数据库名' api_manager)"
  DB_USER="$(ask '给本应用新建的 MySQL 用户名' api_manager)"
  DB_PASS="$(rand 32)"

  # Admin connection used only now, to create the database and a least-privilege user.
  # Local MySQL: connect over the socket so root's auth_socket (Ubuntu/Debian default) works.
  if [[ "$DB_HOST" == 127.0.0.1 || "$DB_HOST" == localhost ]]; then
    MYSQL_ADMIN=(mysql -u root)
  else
    MYSQL_ADMIN=(mysql -h "$DB_HOST" -P "$DB_PORT" -u root)
  fi
  if ! "${MYSQL_ADMIN[@]}" -e 'SELECT 1' >/dev/null 2>&1; then
    read -r -s -p "MySQL root 密码（只用这一次，用来建库建用户，不会保存）: " MYSQL_ROOT_PW </dev/tty; echo
    export MYSQL_PWD="$MYSQL_ROOT_PW"
    "${MYSQL_ADMIN[@]}" -e 'SELECT 1' >/dev/null 2>&1 || die "MySQL root 登录失败"
  fi
  DB_CLIENT_HOST=localhost
  [[ "$DB_HOST" != 127.0.0.1 && "$DB_HOST" != localhost ]] && DB_CLIENT_HOST='%'
  "${MYSQL_ADMIN[@]}" <<SQL
CREATE DATABASE IF NOT EXISTS \`$DB_NAME\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '$DB_USER'@'$DB_CLIENT_HOST' IDENTIFIED BY '$DB_PASS';
CREATE USER IF NOT EXISTS '$DB_USER'@'127.0.0.1' IDENTIFIED BY '$DB_PASS';
ALTER USER '$DB_USER'@'$DB_CLIENT_HOST' IDENTIFIED BY '$DB_PASS';
ALTER USER '$DB_USER'@'127.0.0.1' IDENTIFIED BY '$DB_PASS';
GRANT ALL PRIVILEGES ON \`$DB_NAME\`.* TO '$DB_USER'@'$DB_CLIENT_HOST';
GRANT ALL PRIVILEGES ON \`$DB_NAME\`.* TO '$DB_USER'@'127.0.0.1';
FLUSH PRIVILEGES;
SQL
  unset MYSQL_PWD MYSQL_ROOT_PW
  c_ok "已创建数据库 $DB_NAME 和专用用户 $DB_USER（只有这个库的权限）"

  umask 077
  cat >"$ENV_FILE" <<ENV
# Generated by deploy/install.sh on $(date -Is). Keep this file secret and back it up:
# losing ENCRYPT_SECRET means every stored API key becomes unreadable.
DB_HOST=$DB_HOST
DB_PORT=$DB_PORT
DB_NAME=$DB_NAME
DB_USERNAME=$DB_USER
DB_PASSWORD=$DB_PASS
ENCRYPT_SECRET=$(rand 48)
APP_ORIGIN=$ORIGIN
TRUST_PROXY=1
ENV
  umask 022
  c_ok "已生成 $ENV_FILE（含随机生成的数据库密码和加密密钥）"
else
  c_ok "沿用已有的 $ENV_FILE"
  grep -q "^APP_ORIGIN=$ORIGIN$" "$ENV_FILE" || c_warn "注意：$ENV_FILE 里的 APP_ORIGIN 和当前地址 $ORIGIN 不一致，登录会被 CSRF 校验拒绝"
fi

cat >"$STATE_FILE" <<STATE
PUBLIC_IP=$PUBLIC_IP
HTTPS_PORT=$HTTPS_PORT
APP_PORT=$APP_PORT
STATE

# ---------------------------------------------------------------- 5. build
# Source and node_modules stay owned by root, so `git pull` as root just works;
# the service user can only read them.
c_info "安装依赖并构建（第一次会比较久）"
chown root:"$RUN_AS" "$ENV_FILE"
chmod 640 "$ENV_FILE"
npm ci --no-audit --no-fund
npm run build
npm run db:init
# Build output (not source) belongs to the service user, which needs to write .next/cache at runtime.
chown -R "$RUN_AS":"$RUN_AS" "$APP_DIR/.next"
c_ok "构建和数据库迁移完成"

# ---------------------------------------------------------------- 6. systemd service
cat >/etc/systemd/system/$SERVICE.service <<UNIT
[Unit]
Description=API Manager (Next.js)
After=network.target mysql.service mysqld.service mariadb.service

[Service]
Type=simple
User=$RUN_AS
WorkingDirectory=$APP_DIR
Environment=NODE_ENV=production
ExecStart=$NODE_BIN $APP_DIR/node_modules/next/dist/bin/next start -H 127.0.0.1 -p $APP_PORT
Restart=on-failure
RestartSec=5
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=full
ProtectHome=true

[Install]
WantedBy=multi-user.target
UNIT
if [[ "$RUN_AS" == root || "$APP_DIR" == /home/* || "$APP_DIR" == /root* ]]; then
  sed -i 's/^ProtectHome=true/ProtectHome=false/' /etc/systemd/system/$SERVICE.service
fi
systemctl daemon-reload
systemctl enable "$SERVICE" >/dev/null
systemctl restart "$SERVICE"
for _ in $(seq 1 30); do
  curl -fsS -o /dev/null "http://127.0.0.1:$APP_PORT/login" && break
  sleep 1
done
curl -fsS -o /dev/null "http://127.0.0.1:$APP_PORT/login" \
  || { journalctl -u "$SERVICE" -n 40 --no-pager; die "服务没有启动成功，日志见上方"; }
c_ok "服务 $SERVICE 已启动（127.0.0.1:$APP_PORT，开机自启）"

# ---------------------------------------------------------------- 7. TLS certificate (self-signed for the IP)
if [[ ! -f "$CERT_DIR/cert.pem" ]]; then
  mkdir -p "$CERT_DIR"
  openssl req -x509 -newkey rsa:2048 -nodes -sha256 -days 825 \
    -keyout "$CERT_DIR/key.pem" -out "$CERT_DIR/cert.pem" \
    -subj "/CN=$PUBLIC_IP" -addext "subjectAltName=IP:$PUBLIC_IP" 2>/dev/null
  chmod 600 "$CERT_DIR/key.pem"
  c_ok "已为 $PUBLIC_IP 生成自签名证书（有效期 825 天）"
fi

# ---------------------------------------------------------------- 8. nginx
cat >"$NGINX_CONF" <<NGINX
# API Manager — generated by deploy/install.sh
limit_req_zone \$binary_remote_addr zone=am_login:10m rate=10r/m;

server {
    listen $HTTPS_PORT ssl;
    http2 on;
    server_name $PUBLIC_IP;

    ssl_certificate     $CERT_DIR/cert.pem;
    ssl_certificate_key $CERT_DIR/key.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_session_cache shared:am_ssl:10m;

    client_max_body_size 1m;
    server_tokens off;

    # Extra, coarse brute-force brake in front of the app's own rate limiter.
    location = /api/auth/login {
        limit_req zone=am_login burst=5 nodelay;
        limit_req_status 429;
        proxy_pass http://127.0.0.1:$APP_PORT;
        proxy_set_header Host \$http_host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-Proto https;
    }

    location / {
        proxy_pass http://127.0.0.1:$APP_PORT;
        proxy_set_header Host \$http_host;            # keep :port so app redirects stay on it
        proxy_set_header X-Real-IP \$remote_addr;   # overwrite: clients can't spoof it
        proxy_set_header X-Forwarded-Proto https;
        proxy_read_timeout 120s;                     # single-site group fetch can take up to ~75s
    }
}
NGINX
if ! nginx -t 2>/tmp/am-nginx-test; then
  # Older nginx (< 1.25.1) doesn't know `http2 on;`
  if grep -q 'unknown directive "http2"' /tmp/am-nginx-test; then
    sed -i -e '/^    http2 on;$/d' -e "s/listen $HTTPS_PORT ssl;/listen $HTTPS_PORT ssl http2;/" "$NGINX_CONF"
  fi
  nginx -t || die "nginx 配置检查失败，见上方报错（配置文件：$NGINX_CONF）"
fi
systemctl reload nginx
c_ok "nginx 已在 $HTTPS_PORT 端口提供 HTTPS"

# ---------------------------------------------------------------- 9. firewall hint
if command -v ufw >/dev/null && ufw status | grep -q "Status: active"; then
  ufw allow "$HTTPS_PORT/tcp" >/dev/null && c_ok "ufw 已放行 $HTTPS_PORT/tcp"
elif command -v firewall-cmd >/dev/null && firewall-cmd --state >/dev/null 2>&1; then
  firewall-cmd --permanent --add-port="$HTTPS_PORT/tcp" >/dev/null && firewall-cmd --reload >/dev/null && c_ok "firewalld 已放行 $HTTPS_PORT/tcp"
fi

# ---------------------------------------------------------------- 10. first admin
USER_LIST="$(npm run -s user:list)"   # captured first: grep -q + pipefail can misfire on SIGPIPE
if grep -q '还没有管理员' <<<"$USER_LIST"; then
  echo
  c_info "创建第一个管理员账号"
  ADMIN_NAME="$(ask '管理员用户名' admin)"
  echo "密码要求：至少 12 位，包含大写、小写、数字、符号中的至少三类。输入时不会显示。"
  npm run -s user:create -- "$ADMIN_NAME" </dev/tty
fi

echo
c_ok "部署完成！"
echo "  访问地址：$ORIGIN"
echo "  浏览器会提示「连接不是私密连接」（自签名证书），点「高级」→「继续前往」即可。"
echo "  别忘了在云服务商的安全组里放行 TCP $HTTPS_PORT 端口。"
echo
echo "  常用命令："
echo "    查看日志   journalctl -u $SERVICE -f"
echo "    重启服务   systemctl restart $SERVICE"
echo "    管理账号   cd $APP_DIR && npm run user:list   （user:create / user:passwd / user:disable / auth:unlock ...）"
echo "    升级版本   cd $APP_DIR && git pull && sudo bash deploy/install.sh"
echo
c_warn "请备份 $ENV_FILE —— 丢了里面的 ENCRYPT_SECRET，库里所有 API Key 都无法解密。"
